'use client'
import { useEffect, useState } from 'react'
import { useRouter } from '@/store/router'
import { useAuth } from '@/store/auth'
import { PageHeader, LoadingState, ErrorState } from '../States'
import { GlassCard } from '../GlassCard'
import { StatCard } from '../StatCard'
import { StatusBadge, RoleBadge } from '../Badges'
import { Button } from '@/components/ui/button'
import { apiGet } from '@/lib/client/api'
import { fmtDate, fmtRelative, shortHash } from '@/lib/client/format'
import {
  FileText, Printer, Download, Boxes, ShieldCheck, Activity,
  AlertTriangle, Users, Network, TrendingUp, Clock, Cpu,
} from 'lucide-react'
import { motion } from 'framer-motion'

interface ReportData {
  stats: {
    totalDrugs: number
    verifiedDrugs: number
    pendingTransfers: number
    expiredDrugs: number
    flaggedDrugs: number
    totalTransactions: number
    totalUsers: number
    totalManufacturers: number
    totalDistributors: number
    totalPharmacies: number
    totalVerifications: number
  }
  blockchain: {
    connected: boolean
    chainIntegrity: string
    lastBlock: number
    lastBlockHash: string | null
    lastBlockTime: string | null
    networkStatus: string
    verificationStatus: string
  }
  recentDrugs: any[]
  recentTransactions: any[]
  recentVerifications: any[]
}

export function ReportsView() {
  const { user } = useAuth()
  const { navigate } = useRouter()
  const [data, setData] = useState<ReportData | null>(null)
  const [loading, setLoading] = useState(true)
  const [error, setError] = useState<string | null>(null)

  const load = async () => {
    setLoading(true); setError(null)
    try {
      const d = await apiGet<ReportData>('/api/analytics/dashboard')
      setData(d)
    } catch (e) { setError((e as Error).message) }
    finally { setLoading(false) }
  }
  useEffect(() => { load() }, [])

  if (!user || user.role !== 'ADMIN') {
    return (
      <div className="mx-auto max-w-md py-20 text-center">
        <FileText className="h-10 w-10 text-muted-foreground mx-auto mb-3" />
        <p className="text-muted-foreground">Admin access required to view reports.</p>
        <Button className="mt-4" onClick={() => navigate('dashboard')}>Back to Dashboard</Button>
      </div>
    )
  }

  if (loading) return <LoadingState label="Generating report…" />
  if (error || !data) return <ErrorState description={error ?? undefined} onRetry={load} />

  const { stats, blockchain } = data
  const reportDate = new Date()
  const reportId = `PT-RPT-${reportDate.getFullYear()}${String(reportDate.getMonth() + 1).padStart(2, '0')}${String(reportDate.getDate()).padStart(2, '0')}-${String(reportDate.getHours()).padStart(2, '0')}${String(reportDate.getMinutes()).padStart(2, '0')}`

  return (
    <div className="space-y-6">
      <PageHeader
        icon={<FileText className="h-5 w-5" />}
        title="System Reports"
        subtitle="Comprehensive overview of the PharmaTrace blockchain network."
        actions={
          <div className="flex gap-2">
            <Button variant="outline" size="sm" onClick={() => window.print()}>
              <Printer className="h-4 w-4 mr-1.5" /> Print Report
            </Button>
            <Button size="sm" onClick={() => window.print()}>
              <Download className="h-4 w-4 mr-1.5" /> Export PDF
            </Button>
          </div>
        }
      />

      {/* Report header (print-friendly) */}
      <GlassCard glow="cyan" className="report-header">
        <div className="flex items-start justify-between flex-wrap gap-4">
          <div>
            <div className="text-xs uppercase tracking-[0.18em] text-muted-foreground">PharmaTrace Network Report</div>
            <h2 className="text-2xl font-semibold mt-1">Blockchain Status Summary</h2>
            <div className="mt-2 text-sm text-muted-foreground">
              Report ID: <span className="font-mono">{reportId}</span>
            </div>
            <div className="text-sm text-muted-foreground">
              Generated: {fmtDate(reportDate.toISOString(), true)}
            </div>
            <div className="text-sm text-muted-foreground">
              Generated by: {user.name} ({user.email})
            </div>
          </div>
          <div className="text-right">
            <div className={`inline-flex items-center gap-2 rounded-lg px-3 py-1.5 text-sm font-semibold ${blockchain.chainIntegrity === 'VERIFIED' ? 'bg-emerald-500/15 text-emerald-300' : 'bg-rose-500/15 text-rose-300'}`}>
              <ShieldCheck className="h-4 w-4" />
              Chain Integrity: {blockchain.chainIntegrity}
            </div>
            <div className="mt-2 text-xs text-muted-foreground">Last Block: #{blockchain.lastBlock}</div>
          </div>
        </div>
      </GlassCard>

      {/* Executive summary */}
      <div>
        <h3 className="text-lg font-semibold mb-3">Executive Summary</h3>
        <div className="grid gap-4 sm:grid-cols-2 lg:grid-cols-4">
          <StatCard label="Total Drugs" value={stats.totalDrugs} accent="cyan" icon={<Boxes className="h-5 w-5" />} />
          <StatCard label="Verified" value={stats.verifiedDrugs} accent="emerald" icon={<ShieldCheck className="h-5 w-5" />} />
          <StatCard label="Flagged" value={stats.flaggedDrugs} accent="rose" icon={<AlertTriangle className="h-5 w-5" />} />
          <StatCard label="Transactions" value={stats.totalTransactions} accent="violet" icon={<Activity className="h-5 w-5" />} />
        </div>
      </div>

      {/* User summary */}
      <div>
        <h3 className="text-lg font-semibold mb-3">Network Participants</h3>
        <div className="grid gap-4 sm:grid-cols-2 lg:grid-cols-4">
          <StatCard label="Total Users" value={stats.totalUsers} accent="cyan" icon={<Users className="h-5 w-5" />} />
          <StatCard label="Manufacturers" value={stats.totalManufacturers} accent="violet" icon={<Boxes className="h-5 w-5" />} />
          <StatCard label="Distributors" value={stats.totalDistributors} accent="sky" icon={<TrendingUp className="h-5 w-5" />} />
          <StatCard label="Pharmacies" value={stats.totalPharmacies} accent="emerald" icon={<ShieldCheck className="h-5 w-5" />} />
        </div>
      </div>

      {/* Blockchain health */}
      <GlassCard>
        <h3 className="font-semibold mb-3 flex items-center gap-2">
          <Network className="h-4 w-4 text-cyan-300" />
          Blockchain Health
        </h3>
        <div className="grid sm:grid-cols-2 lg:grid-cols-4 gap-3 text-sm">
          <HealthItem label="Network Status" value={blockchain.networkStatus} ok={blockchain.networkStatus === 'ONLINE'} />
          <HealthItem label="Chain Integrity" value={blockchain.chainIntegrity} ok={blockchain.chainIntegrity === 'VERIFIED'} />
          <HealthItem label="Verification Status" value={blockchain.verificationStatus} ok />
          <HealthItem label="Last Block" value={`#${blockchain.lastBlock}`} ok mono />
        </div>
        {blockchain.lastBlockTime && (
          <div className="mt-3 text-xs text-muted-foreground flex items-center gap-1.5">
            <Clock className="h-3 w-3" />
            Last block sealed: {fmtRelative(blockchain.lastBlockTime)}
          </div>
        )}
      </GlassCard>

      {/* Recent activity table */}
      <GlassCard>
        <h3 className="font-semibold mb-3">Recent Blockchain Transactions</h3>
        <div className="overflow-x-auto scrollbar-thin">
          <table className="w-full text-sm">
            <thead className="text-left text-xs uppercase tracking-wider text-muted-foreground border-b border-border/60">
              <tr>
                <th className="py-2 pr-3">Type</th>
                <th className="py-2 pr-3">Drug</th>
                <th className="py-2 pr-3 hidden md:table-cell">Block</th>
                <th className="py-2 pr-3">Timestamp</th>
              </tr>
            </thead>
            <tbody>
              {data.recentTransactions.slice(0, 10).map((tx) => (
                <tr key={tx.id} className="border-b border-border/40">
                  <td className="py-2 pr-3 text-xs font-medium">{tx.type.replace(/_/g, ' ')}</td>
                  <td className="py-2 pr-3">{tx.drug?.drugName ?? '—'}</td>
                  <td className="py-2 pr-3 hidden md:table-cell font-mono text-xs">#{tx.block?.blockNumber ?? '—'}</td>
                  <td className="py-2 pr-3 text-xs text-muted-foreground">{fmtRelative(tx.timestamp)}</td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </GlassCard>

      {/* Recent drugs table */}
      <GlassCard>
        <h3 className="font-semibold mb-3">Registered Drug Batches</h3>
        <div className="overflow-x-auto scrollbar-thin">
          <table className="w-full text-sm">
            <thead className="text-left text-xs uppercase tracking-wider text-muted-foreground border-b border-border/60">
              <tr>
                <th className="py-2 pr-3">Drug Name</th>
                <th className="py-2 pr-3">Batch</th>
                <th className="py-2 pr-3 hidden md:table-cell">Manufacturer</th>
                <th className="py-2 pr-3">Status</th>
              </tr>
            </thead>
            <tbody>
              {data.recentDrugs.slice(0, 10).map((d) => (
                <tr key={d.id} className="border-b border-border/40">
                  <td className="py-2 pr-3 font-medium">{d.drugName}</td>
                  <td className="py-2 pr-3 font-mono text-xs">{d.batchNumber}</td>
                  <td className="py-2 pr-3 hidden md:table-cell text-muted-foreground">{d.manufacturer?.organization ?? d.manufacturer?.name ?? '—'}</td>
                  <td className="py-2 pr-3"><StatusBadge status={d.status} /></td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </GlassCard>

      {/* Footer */}
      <div className="text-center text-xs text-muted-foreground py-4 report-footer">
        <p>PharmaTrace Blockchain Network Report · {reportId}</p>
        <p className="mt-1">Generated on {fmtDate(reportDate.toISOString(), true)} · Academic Prototype — Not a Production Regulatory System</p>
      </div>
    </div>
  )
}

function HealthItem({ label, value, ok, mono }: { label: string; value: string; ok?: boolean; mono?: boolean }) {
  return (
    <div className="rounded-lg border border-border/40 bg-muted/20 p-3">
      <div className="text-[10px] uppercase tracking-wider text-muted-foreground">{label}</div>
      <div className={`mt-1 text-sm font-semibold ${mono ? 'font-mono' : ''} ${ok === false ? 'text-rose-300' : 'text-emerald-300'}`}>
        {value}
      </div>
    </div>
  )
}
